import importlib.util
from pathlib import Path
import sys
import unittest

ROOT = Path(__file__).resolve().parents[2]
SCRIPTS = ROOT/'rusix/scripts'
sys.path.insert(0, str(SCRIPTS))
import saved_clang_command as saved
spec = importlib.util.spec_from_file_location('task_selection', SCRIPTS/'verify-task-construction.py')
m = importlib.util.module_from_spec(spec); spec.loader.exec_module(m)


def command_record():
    # Literal modeled command; parser tests do not execute a compiler.
    includes = ' '.join('-include '+p for p in saved.REQUIRED_INCLUDES)
    return ('savedcmd_kernel/fork.o := clang -Wp,-MMD,kernel/.fork.o.d '
            +includes+' -D__KERNEL__ --target=x86_64-linux-gnu -std=gnu11 '
            '-c -o kernel/fork.o /src/kernel/fork.c ; '
            +' '.join(saved.PLAIN_OBJTOOL)+'\nsource_kernel/fork.o := /src/kernel/fork.c\n')


class Selection(unittest.TestCase):
    def test_original_full_file_reconstruction(self):
        text = (ROOT/'kernel/fork.c').read_text()
        m.original_policy(text)
        for changed in (text+'\n', text.replace('return rusix_dup_task_struct(orig, node);', 'node++; return rusix_dup_task_struct(orig, node);'),
                        text.replace('tsk->splice_pipe = NULL;', 'tsk->splice_pipe = orig->splice_pipe;'),
                        text.replace('#else\nstatic struct task_struct *dup_task_struct(', '#else\n\nstatic struct task_struct *dup_task_struct(')):
            with self.assertRaises(ValueError): m.original_policy(changed)

    def test_profiles_match_server_and_only_selector_differs(self):
        configs = [m.config_values((ROOT/f'rusix/configs/x86_64-task-construction-{i}.config').read_text()) for i in ('c', 'rust')]
        self.assertEqual(m.compare(*configs), [m.SELECTOR])
        target = m.config_values((ROOT/'rusix/configs/x86_64-server.config').read_text())
        for profile, config in zip(m.PROFILES, configs):
            # Architecture-selected symbols are generated by real Kconfig later.
            config.update(CONFIG_X86_64='y', CONFIG_THREAD_INFO_IN_TASK='y')
            m.check_config(profile, config, target)
            for key in ('CONFIG_SMP', 'CONFIG_SECCOMP', 'CONFIG_EXT4_FS', 'CONFIG_PROVE_LOCKING'):
                bad = config | {key: 'n'}
                with self.assertRaises(ValueError): m.check_config(profile, bad, target)
            for key in m.EXCLUDED:
                with self.assertRaises(ValueError): m.check_config(profile, config | {'CONFIG_'+key:'y'}, target)
            bad = config.copy(); del bad[m.SELECTOR]
            with self.assertRaises(ValueError): m.check_config(profile, bad, target)
        with self.assertRaises(ValueError): m.check_config('server', configs[0], target)
        with self.assertRaises(ValueError): m.compare(configs[0], configs[1] | {'CONFIG_SMP':'n'})

    def test_duplicate_config_rejected(self):
        with self.assertRaises(ValueError): m.config_values('CONFIG_SMP=y\nCONFIG_SMP=y\n')

    def test_rust_preprocessed_exact_forwarder(self):
        body = 'static struct task_struct *dup_task_struct(struct task_struct *orig, int node) { return rusix_dup_task_struct(orig, node); }'
        m.check_preprocessed(body, True)
        for bad in (body+body, body.replace('return ', 'node++; return '), body.replace('orig, node', 'orig, 0')):
            with self.assertRaises(ValueError): m.check_preprocessed(bad, True)
        with self.assertRaises(ValueError): m.check_preprocessed(body, False)

    def test_c_transaction_landmarks(self):
        body = ('static struct task_struct *dup_task_struct(void) {'
                'alloc_task_struct_node(node); arch_dup_task_struct(tsk,orig);'
                'alloc_thread_stack_node(tsk,node); account_kernel_stack(tsk,1);'
                'dup_user_cpus_ptr(tsk,orig,node); free_stack: exit_task_stack_account(tsk);'
                'free_thread_stack(tsk); free_tsk: free_task_struct(tsk); }')
        m.check_preprocessed(body, False)
        with self.assertRaises(ValueError): m.check_preprocessed(body.replace('free_thread_stack(tsk);', ''), False)
        with self.assertRaises(ValueError): m.check_preprocessed(body, True)

    def test_executable_relocation_required(self):
        text = ' 12: e8 00 00 00 00 callq 0\n 13: R_X86_64_PLT32 rusix_dup_task_struct-0x4\n'
        m.check_relocations(text, True); m.check_relocations('', False)
        for bad in ('', text.replace('callq', 'movq'), text.replace('PLT32', '64')):
            with self.assertRaises(ValueError): m.check_relocations(bad, True)
        with self.assertRaises(ValueError): m.check_relocations(text, False)

    def test_unique_symbol_definition(self):
        line = '0000000000000000 T rusix_dup_task_struct\n'
        m.bridge_definition(line, True); m.bridge_definition('', False)
        for bad in ('', line+line, line.replace(' T ', ' t '), line.replace(' T ', ' D ')):
            with self.assertRaises(ValueError): m.bridge_definition(bad, True)
        with self.assertRaises(ValueError): m.bridge_definition(line, False)

    def test_archive_members(self):
        m.archive_members('kernel/fork.o\nkernel/task_construction_rust.o\n', True)
        m.archive_members('kernel/fork.o\n', False)
        for bad in ('', 'fork.o\nfork.o\ntask_construction_rust.o\n',
                    'fork.o\n', 'fork.o\ntask_construction_rust.o\ntask_construction_other.o\n'):
            with self.assertRaises(ValueError): m.archive_members(bad, True)

    def test_saved_command_no_shell_or_unknown_flags(self):
        record = command_record()
        argv = saved.command(record, Path('fork.i'))
        self.assertEqual(argv[-3:], ['-E', '-o', 'fork.i'])
        self.assertNotIn('-c', argv)
        for token in ('; touch /tmp/x', '&& touch /tmp/x', '$(touch /tmp/x)', '`touch /tmp/x`',
                      '-fplugin=evil.so', '-include /tmp/evil.h', '-DOVERRIDE=y', '@response'):
            bad = record.replace(' -c ', ' '+token+' -c ')
            with self.assertRaises(ValueError): saved.command(bad, Path('fork.i'))
        for bad in (record+record, record.replace('/src/kernel/fork.c', '/src/kernel/exec.c'),
                    record.replace('clang ', '/tmp/clang '), record.replace(' -c ', ' -c -c '),
                    record.replace(' --orc', ' --unknown')):
            with self.assertRaises(ValueError): saved.command(bad, Path('fork.i'))

    def test_hardened_postpass_only(self):
        record = command_record().replace(' '.join(saved.PLAIN_OBJTOOL), ' '.join(saved.HARDENED_OBJTOOL))
        saved.command(record, Path('fork.i'))
        with self.assertRaises(ValueError): saved.command(record.replace('--prefix=16', '--prefix=32'), Path('fork.i'))


if __name__ == '__main__': unittest.main()
